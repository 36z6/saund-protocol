#!/usr/bin/env python3
"""
saund-reverse — MVP skeleton v0.1
Lossy audio -> SAUND template. Confidence-tagged, never silent.
Requires: pip install librosa numpy
Usage: python saund-reverse.py track.mp3 -o track.saund
"""
import argparse
import numpy as np
try:
    import librosa
except ImportError:
    raise SystemExit("librosa missing: pip install librosa")

# Krumhansl-style templates (simplified) for key estimation
KEY_NAMES = ["C","C#","D","D#","E","F","F#","G","G#","A","A#","B"]
MAJOR_T = [6.35,2.23,3.48,2.33,4.38,4.09,2.52,5.19,2.39,3.66,2.29,2.88]
MINOR_T = [6.33,2.68,3.52,5.38,2.60,3.53,2.54,4.75,3.98,2.69,3.34,3.17]

def estimate_key(chroma):
    best = (None, -1)
    for shift in range(12):
        for mode, tpl in (("major", MAJOR_T), ("minor", MINOR_T)):
            rolled = np.roll(tpl, shift)
            score = float(np.corrcoef(chroma.mean(axis=1), rolled)[0, 1])
            if score > best[1]:
                best = (f"{KEY_NAMES[shift]} {mode}", score)
    return best  # (key, confidence -1..1)

def suggest_arc(energy_curve, n=8):
    """Heuristic: low->I/O, mid->G/R/P, high->K/S/F. LOSSY, flagged."""
    codes = []
    lo, hi = np.percentile(energy_curve, [25, 75])
    for i, e in enumerate(energy_curve):
        if i == 0: codes.append("I")
        elif i == n - 1: codes.append("O")
        elif e >= hi: codes.append("K" if i < n // 2 else "F")
        elif e <= lo: codes.append("R" if i < n // 2 else "P")
        else: codes.append("G" if i < n // 2 else "S")
    return codes

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("audio"); ap.add_argument("-o", "--out", default=None)
    ap.add_argument("--sections", type=int, default=8)
    args = ap.parse_args()

    y, sr = librosa.load(args.audio, sr=None, mono=True)
    tempo, _ = librosa.beat.beat_track(y=y, sr=sr)
    chroma = librosa.feature.chroma_cqt(y=y, sr=sr)
    key, key_conf = estimate_key(chroma)
    rms = librosa.feature.rms(y=y)[0]
    bounds = np.linspace(0, len(rms), args.sections + 1).astype(int)
    energy = [float(rms[a:b].mean()) for a, b in zip(bounds[:-1], bounds[1:])]
    arc = suggest_arc(energy, args.sections)
    dur = float(librosa.get_duration(y=y))
    sec_dur = round(dur / args.sections)

    out = args.out or args.audio.rsplit(".", 1)[0] + ".saund"
    lines = [
        f"# AUTO-GENERATED by saund-reverse v0.1 (LOSSY, confidence-tagged)",
        f"# tempo_conf=high key_conf={key_conf:.2f} arc_conf=LOW (fill manually)",
        f"[GLOBAL: tempo={int(tempo)} BPM; key={key}; source=reverse-engineered;",
        f"  CONFIDENCE: arc=LOW, key=MEDIUM, tempo=HIGH. VERIFY BEFORE USE.]",
        f"[ARC: {' '.join(arc)}]",
        f"[DUR-PLAN: TOTAL={int(dur//60)}:{int(dur%60):02d}; "
        + ",".join(f"{c}={sec_dur}" for c in arc) + "]",
        "# TODO(manual): INST-MAP, GRV-MAP, LEAD-MAP, VOC-MAP, FID-MAP",
        "# TODO(manual): Zone B vocal text",
        "",
    ] + [f"[{c}]" for c in arc]
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"[saund-reverse] wrote {out}")
    print(f"[saund-reverse] tempo={int(tempo)} key={key} ({key_conf:.2f}) "
          f"duration={dur:.1f}s arc={' '.join(arc)} [LOW-CONF]")

if __name__ == "__main__":
    main()
